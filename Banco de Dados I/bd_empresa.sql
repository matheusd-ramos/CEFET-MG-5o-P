-- Evolução de estrutura (DDL)
ALTER TABLE DEPARTAMENTO ADD (
    CPF_GERENTE VARCHAR2(11) REFERENCES FUNCIONARIO(CPF) UNIQUE,
    DATA_INICIO DATE NOT NULL
);

ALTER TABLE FUNCIONARIO ADD (
    CPF_SUPERVISOR VARCHAR2(11) REFERENCES FUNCIONARIO(CPF),
    SALARIO NUMBER(10) NOT NULL
);

CREATE TABLE DEPENDENTE (
    CPF_FUNCIONARIO VARCHAR2(11) REFERENCES FUNCIONARIO(CPF) ON DELETE CASCADE,
    NOME VARCHAR2(50),
    DATA_NASCIMENTO DATE DEFAULT SYSDATE NOT NULL,
    SEXO CHAR(1) CHECK (SEXO IN ('M', 'F')),
    PRIMARY KEY (CPF_FUNCIONARIO, NOME),
    PARENTESCO VARCHAR2(15)
);

CREATE TABLE LOCAL_DEPARTAMENTO (
    NUMERO NUMBER(5) REFERENCES DEPARTAMENTO(NUMERO) ON DELETE CASCADE,
    LOCAL VARCHAR2(30),
    PRIMARY KEY (NUMERO, LOCAL)
);

CREATE TABLE PROJETO (
    NUMERO_PROJETO NUMBER(5),
    NOME_PROJETO VARCHAR2(50) NOT NULL,
    LOCAL_PROJETO VARCHAR2(50) NOT NULL,
    NUMERO_DEPARTAMENTO NUMBER(5) REFERENCES DEPARTAMENTO(NUMERO),
    PRIMARY KEY (NUMERO_PROJETO)
);

CREATE TABLE TRABALHA_EM (
    CPF_FUNCIONARIO VARCHAR2(11) REFERENCES FUNCIONARIO(CPF) ON DELETE CASCADE,
    NUMERO_PROJETO NUMBER(5) REFERENCES PROJETO(NUMERO_PROJETO) ON DELETE CASCADE,
    HORAS NUMBER(4,1),
    PRIMARY KEY (CPF_FUNCIONARIO, NUMERO_PROJETO)
);

